def go_source():
    out = ['// Code generated by tools/genstamps.py; DO NOT EDIT.', '', 'package app', '',
           '// stampDefs: black silhouettes in multicolor pixels (\'#\' = set).',
           'var stampDefs = []stampDef{']
    for name, cat, w, h, rows in STAMPS:
        out.append('\t{name: %s, cat: %s, w: %d, h: %d, rows: []string{' % (gostr(name), gostr(cat), w // 2, h))
        for r in rows:
            out.append('\t\t%s,' % gostr(r))
        out.append('\t}},')
    out.append('}')
    return '\n'.join(out) + '\n'


def gostr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def sheet(path):
    cell = 72
    cols = 12
    n = len(STAMPS)
    rows = (n + cols - 1) // cols
    im = Image.new('RGB', (cols * cell, rows * (cell + 12)), (220, 220, 220))
    d = ImageDraw.Draw(im)
    for k, (name, cat, w, h, bits) in enumerate(STAMPS):
        cx, cy = (k % cols) * cell, (k // cols) * (cell + 12)
        for y, r in enumerate(bits):
            for x, ch in enumerate(r):
                if ch == '#':
                    d.rectangle([cx + 4 + x * 2, cy + 4 + y, cx + 4 + x * 2 + 1, cy + 4 + y], fill=(0, 0, 0))
        d.text((cx + 2, cy + cell - 2), name[:12], fill=(60, 60, 160))
    im = im.resize((im.width * 2, im.height * 2), Image.NEAREST)
    im.save(path)


