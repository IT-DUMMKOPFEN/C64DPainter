# Generates the stamp silhouettes (internal/app/stamps_data.go).
#
# Every stamp is drawn with simple shapes in screen pixels (320 x 200 grid),
# rendered 8x larger and reduced to multicolor pixels (2 x 1 screen pixels):
# a multicolor pixel is set when the shape covers enough of it. The result
# is one color plus transparent, so it always fits the multicolor rules.
#
#   python3 tools/genstamps.py [contact-sheet.png]
import math, sys
from PIL import Image, ImageDraw

S = 8  # render scale
STAMPS = []


class Pic:
    def __init__(self, w, h):
        self.w, self.h = w, h
        self.im = Image.new('L', (w * S, h * S), 0)
        self.d = ImageDraw.Draw(self.im)

    def _p(self, pts):
        return [(x * S, y * S) for x, y in pts]

    def ell(self, cx, cy, rx, ry, c=255):
        self.d.ellipse([(cx - rx) * S, (cy - ry) * S, (cx + rx) * S, (cy + ry) * S], fill=c)

    def circ(self, cx, cy, r, c=255):
        self.ell(cx, cy, r, r, c)

    def poly(self, pts, c=255):
        self.d.polygon(self._p(pts), fill=c)

    def rect(self, x0, y0, x1, y1, c=255):
        self.d.rectangle([x0 * S, y0 * S, x1 * S - 1, y1 * S - 1], fill=c)

    def line(self, pts, w, c=255):
        """thick polyline with round joints and ends"""
        for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
            dx, dy = x1 - x0, y1 - y0
            l = math.hypot(dx, dy) or 1
            nx, ny = -dy / l * w / 2, dx / l * w / 2
            self.poly([(x0 + nx, y0 + ny), (x1 + nx, y1 + ny), (x1 - nx, y1 - ny), (x0 - nx, y0 - ny)], c)
        for x, y in pts:
            self.circ(x, y, w / 2, c)

    def arc(self, cx, cy, r, a0, a1, w, c=255, n=24):
        pts = [(cx + r * math.cos(math.radians(a0 + (a1 - a0) * i / n)),
                cy + r * math.sin(math.radians(a0 + (a1 - a0) * i / n))) for i in range(n + 1)]
        self.line(pts, w, c)

    def cut(self):
        return 0

    def bits(self, thr=0.42):
        mw, mh = self.w // 2, self.h
        px = self.im.load()
        rows = []
        for j in range(mh):
            r = ''
            for i in range(mw):
                tot = 0
                for yy in range(j * S, j * S + S):
                    for xx in range(i * 2 * S, i * 2 * S + 2 * S, 2):
                        tot += px[xx, yy]
                cov = tot / (255.0 * S * S)
                r += '#' if cov >= thr else '.'
            rows.append(r)
        return rows


def stamp(name, cat, w, h):
    def deco(f):
        p = Pic(w, h)
        f(p)
        STAMPS.append((name, cat, w, h, p.bits()))
        return f
    return deco


def mirror_pts(pts, w):
    return [(w - x, y) for x, y in pts]


# ---------------------------------------------------------------- people
#
# A figure in a 32 x 64 frame: joints in screen pixels.

def figure(p, head, neck, hip, arms, legs, hr=4.6, body=7.0, limb=4.2, arm=3.6, skirt=None, dx=0, dy=0):
    def t(q):
        return (q[0] + dx, q[1] + dy)
    hx, hy = t(head)
    p.circ(hx, hy, hr)
    nx, ny = t(neck)
    ix, iy = t(hip)
    # torso: a tapered quad from the shoulders to the hips
    ang = math.atan2(iy - ny, ix - nx)
    px_, py_ = -math.sin(ang), math.cos(ang)
    sw, hw = body / 2 + 0.6, body / 2 - 0.3
    p.poly([(nx + px_ * sw, ny + py_ * sw), (nx - px_ * sw, ny - py_ * sw),
            (ix - px_ * hw, iy - py_ * hw), (ix + px_ * hw, iy + py_ * hw)])
    p.line([(hx, hy), (nx, ny)], 3.4)
    for a in arms:
        p.line([(nx, ny + 1.5)] + [t(q) for q in a], arm)
        hx2, hy2 = t(a[-1])
        p.circ(hx2, hy2, arm / 2 + 0.5)
    for l in legs:
        p.line([(ix, iy)] + [t(q) for q in l[:-1]], limb)
        fx, fy = t(l[-2])
        tx, ty = t(l[-1])
        p.line([(fx, fy), (tx, ty)], limb * 0.8)
    if skirt:
        p.poly([t(q) for q in skirt])


