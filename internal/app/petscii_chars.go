func withInverse(codes []int) []int {
	out := append([]int(nil), codes...)
	for _, c := range codes {
		out = append(out, c|128)
	}
	return out
}

func codeRange(a, b int) []int {
	var out []int
	for c := a; c <= b; c++ {
		out = append(out, c)
	}
	return out
}

