// drawIcon zeichnet ein 16×16-Symbol.
func drawIcon(m *gfx.Image, name string, x, y int, fg, accent uint32) {
	d := iconData[name]
	for yy, row := range d {
		for xx, ch := range row {
			switch ch {
			case '#':
				m.Set(x+xx, y+yy, fg)
			case '+':
				m.BlendPix(x+xx, y+yy, fg, 90)
			case 'o':
				m.Set(x+xx, y+yy, accent)
			}
		}
	}
}

// drawSplitIcon zeichnet ein geteiltes Symbol (oben links Umriss, unten rechts gefüllt).
func drawSplitIcon(m *gfx.Image, outline, filled string, x, y int, fg, dim uint32) {
	a, b := iconData[outline], iconData[filled]
	for yy := 0; yy < 16; yy++ {
		for xx := 0; xx < 16; xx++ {
			var ch byte
			if xx+yy < 16 {
				ch = a[yy][xx]
			} else {
				ch = b[yy][xx]
			}
			if ch == '#' {
				m.Set(x+xx, y+yy, fg)
			}
		}
	}
	_ = dim
}
