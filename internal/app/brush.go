package app

import "math"

// Pinselformen
const (
	BrushRound = iota
	BrushSquare
	BrushDiamond // a square rotated by 45°
	BrushCustom
)

type pt struct{ X, Y int }

// Stamp ist ein Pinselabdruck: Versätze und (bei eigenem Pinsel) Farben.
type Stamp struct {
	Offs   []pt
	Cols   []int8 // nil = aktuelle Farbe; sonst Farbe je Versatz
	W, H   int
	HX, HY int // Hotspot
}

// CustomBrush ist ein aus einer Auswahl erzeugter Pinsel.
type CustomBrush struct {
	W, H int
	Pix  []int8 // -1 = durchsichtig
}

func (b *CustomBrush) clone() *CustomBrush {
	c := &CustomBrush{W: b.W, H: b.H, Pix: append([]int8(nil), b.Pix...)}
	return c
}

// brushDims liefert Breite (Bildpunkte) und Höhe für eine Pinselgröße.
func brushDims(size int, aspect bool) (int, int) {
	h := size
	w := size
	if aspect {
		w = (size + 1) / 2
	}
	if w < 1 {
		w = 1
	}
	return w, h
}

// makeStamp baut den Pinselabdruck.
func makeStamp(shape, size int, aspect bool, cb *CustomBrush) *Stamp {
	if shape == BrushCustom && cb != nil {
		s := &Stamp{W: cb.W, H: cb.H, HX: cb.W / 2, HY: cb.H / 2}
		for y := 0; y < cb.H; y++ {
			for x := 0; x < cb.W; x++ {
				c := cb.Pix[y*cb.W+x]
				if c >= 0 {
					s.Offs = append(s.Offs, pt{x - s.HX, y - s.HY})
					s.Cols = append(s.Cols, c)
				}
			}
		}
		return s
	}
	w, h := brushDims(size, aspect)
	s := &Stamp{W: w, H: h, HX: (w - 1) / 2, HY: (h - 1) / 2}
	for y := 0; y < h; y++ {
		for x := 0; x < w; x++ {
			fx := (float64(x) + 0.5 - float64(w)/2) / (float64(w) / 2)
			fy := (float64(y) + 0.5 - float64(h)/2) / (float64(h) / 2)
			if shape == BrushRound && size > 2 && fx*fx+fy*fy > 1.08 {
				continue
			}
			if shape == BrushDiamond && size > 2 && diamondCover(x, y, w, h) < 0.24 {
				continue
			}
			s.Offs = append(s.Offs, pt{x - s.HX, y - s.HY})
		}
	}
	return s
}

// diamondCover returns how much of pixel (x, y) lies inside a diamond
// (square rotated by 45°) that fills a w×h box.
func diamondCover(x, y, w, h int) float64 {
	const n = 16
	in := 0
	for sy := 0; sy < n; sy++ {
		for sx := 0; sx < n; sx++ {
			fx := (float64(x) + (float64(sx)+0.5)/n - float64(w)/2) / (float64(w) / 2)
			fy := (float64(y) + (float64(sy)+0.5)/n - float64(h)/2) / (float64(h) / 2)
			if math.Abs(fx)+math.Abs(fy) <= 1 {
				in++
			}
		}
	}
	return float64(in) / (n * n)
}

